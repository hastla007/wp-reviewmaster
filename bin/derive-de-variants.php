<?php
/**
 * Derive the regional German translations from the two maintained ones (SET-RC-14):
 *
 *   de_AT <- de_DE         ("du", unchanged texts)
 *   de_CH <- de_DE_formal  ("Sie", "ß" written as "ss" as in Swiss German)
 *
 * Without these files a site in de_AT or de_CH would fall back to the English source strings.
 * Only de_DE and de_DE_formal are edited by hand; run this script (or bin/compile-translations.php,
 * which calls it) after changing them.
 *
 *   php bin/derive-de-variants.php           # write languages/review-captain-de_AT.po and -de_CH.po
 *   php bin/derive-de-variants.php --check   # exit 1 if they are not up to date
 */

$root     = dirname( __DIR__ );
$check    = in_array( '--check', $argv, true );
$variants = array(
	'de_AT' => array( 'de_DE', 'German (Austria)', static fn( string $s ): string => $s ),
	'de_CH' => array( 'de_DE_formal', 'German (Switzerland)', static fn( string $s ): string => str_replace( 'ß', 'ss', $s ) ),
);
$stale    = array();
foreach ( $variants as $locale => list( $base, $team, $convert ) ) {
	$lines  = file( $root . "/languages/review-captain-$base.po", FILE_IGNORE_NEW_LINES );
	$out    = array();
	$in_str = false; // Inside a msgstr (continuation lines start with a quote).
	foreach ( $lines as $line ) {
		if ( str_starts_with( $line, '"Language: ' ) ) {
			$line = '"Language: ' . $locale . '\n"';
		} elseif ( str_starts_with( $line, '"Language-Team: ' ) ) {
			$line = '"Language-Team: ' . $team . '\n"';
		} elseif ( str_starts_with( $line, 'msgstr' ) || ( $in_str && str_starts_with( $line, '"' ) ) ) {
			$line = $convert( $line );
		}
		$in_str = str_starts_with( $line, 'msgstr' ) || ( $in_str && str_starts_with( $line, '"' ) );
		$out[]  = $line;
	}
	$content = "# Generated by bin/derive-de-variants.php from review-captain-$base.po – do not edit.\n" . implode( "\n", $out ) . "\n";
	$file    = $root . "/languages/review-captain-$locale.po";
	if ( $check ) {
		if ( ! is_file( $file ) || file_get_contents( $file ) !== $content ) {
			$stale[] = basename( $file );
		}
	} else {
		file_put_contents( $file, $content );
		echo "$locale: derived from $base\n";
	}
}
if ( $stale ) {
	fwrite( STDERR, 'out of date: ' . implode( ', ', $stale ) . " (run php bin/derive-de-variants.php)\n" );
	exit( 1 );
}
